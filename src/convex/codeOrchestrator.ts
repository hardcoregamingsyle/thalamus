// Cap on tasks dispatched at once per run. Every concurrent task is a live
// model call, and the provider chain (lib/agentCore.ts) has shared rate
// limits and learned cooldowns (lib/providerCooldowns.ts) that apply
// platform-wide, across every run and the live pipeline — not per run. Letting
// one run's plan fan out without bound would hammer every seat at once and
// trip cooldowns for everything else sharing the chain. 4 keeps a single
// run's burst well inside what a free-tier seat tolerates.
const MAX_CONCURRENT_TASKS = 4;

// A task's whole loop lives inside ONE action, so Convex's 10-minute kill is
// the real ceiling — not maxTurns. Every budget below is measured against the
// action's own start so a task always finishes deliberately, writing down what
// it did, instead of being killed mid-turn and leaving the row in "running"
// until finishTask never comes.
const TASK_WALL_CLOCK_MS = 8 * 60 * 1000;
const TURN_MODEL_DEADLINE_MS = 3 * 60 * 1000;
const COMMAND_WAIT_MS = 3 * 60 * 1000;
// Below this there is not enough left for a model call worth making.
const MIN_TURN_MS = 45 * 1000;
const COMMAND_POLL_MS = 4000;
// Plans are written by a model, so maxTurns is clamped rather than trusted.
const DEFAULT_TASK_TURNS = 4;
const MAX_TASK_TURNS = 8;

const TERMINAL_RUN_STATUSES = new Set(["completed", "cancelled", "failed"]);

function toSchedulable(tasks: Doc<"codeTasks">[]): SchedulableTask[] {
  return tasks.map((t) => ({ id: t._id, status: t.status, dependencies: t.dependencies }));
}

// The branch's files, which are what every agent reads and writes. Same store
// the legacy pipeline uses, so a run here and a run there see one project.
async function branchFiles(ctx: QueryCtx, branchId: string) {
  const rows = await ctx.db
    .query("codeFiles")
    .withIndex("by_branch", (q) => q.eq("branchId", branchId))
    .take(1000);
  return rows.map((r) => ({ filepath: r.filepath, content: r.content }));
}

// Waits for a task's own commands, and answers "what happened" rather than
// throwing. A command that never gets picked up is a real outcome the agent
// has to be told about — silence would have it assume success.
async function waitForCommands(
  ctx: { runQuery: (ref: typeof getTaskCommandsRef, args: { ids: Id<"codeCommands">[] }) => Promise<{ command: string; status: string; output?: string; exitCode?: number }[]> },
  ids: Id<"codeCommands">[],
  budgetMs: number,
) {
  const until = Date.now() + budgetMs;
  let last = await ctx.runQuery(getTaskCommandsRef, { ids });
  while (Date.now() < until) {
    if (last.every((r) => r.status === "completed" || r.status === "failed")) return last;
    await new Promise((r) => setTimeout(r, COMMAND_POLL_MS));
    last = await ctx.runQuery(getTaskCommandsRef, { ids });
  }
  // Out of time. Report what each command actually reached — a still-pending
  // command is not a passing one, and the agent is told so in those words.
  return last;
}

export const startRun = mutation({
  args: {
    token: v.string(),
    branchId: v.string(),
    prompt: v.string(),
    // Optional pre-built plan. Ids are plain strings chosen by whatever
    // produced the plan; they exist only to express dependencies before real
    // Convex ids exist and are translated below. Omitted on the normal path —
    // the run plans itself (planRun) from the prompt.
    plan: v.optional(
      v.array(
        v.object({
          id: v.string(),
          title: v.string(),
          description: v.optional(v.string()),
          agent: v.optional(v.string()),
          dependencies: v.optional(v.array(v.string())),
        }),
      ),
    ),
  },
  handler: async (ctx, args) => {
    const session = await requireSession(ctx, args.token);
    const { branch } = await assertBranchOwner(ctx, session.userId, args.branchId);
    const now = Date.now();
    // "auto" is the only mode. `ask` and `read_only` were modelled and never
    // implemented, and a run that stops to ask is the human-in-the-loop this
    // engine exists to remove — the column stays in the schema for old rows,
    // but nothing writes anything else.
    const runId = await ctx.db.insert("codeRuns", { branchId: args.branchId, projectId: branch.projectId, userId: session.userId, prompt: args.prompt.trim(), status: "queued", permissionMode: "auto", createdAt: now, updatedAt: now });

    if (args.plan && args.plan.length > 0) {
      // Pass 1: insert every task so a real Convex id exists for each plan
      // entry, then pass 2 translates each entry's string-id dependencies into
      // those real ids. An entry naming a dependency id outside the plan is
      // dropped rather than failing the insert — a typo in a model-authored
      // plan should not sink the run before it starts.
      const idMap = new Map<string, Id<"codeTasks">>();
      const inserted: { taskId: Id<"codeTasks">; dependsOn: string[] }[] = [];
      for (const entry of args.plan) {
        const taskId = await ctx.db.insert("codeTasks", {
          runId,
          title: entry.title,
          description: entry.description,
          agent: normalizeAgent(entry.agent ?? "Coder"),
          status: "queued",
          dependencies: [],
          allowedTools: ["filesystem", "terminal", "mcp"],
          maxTurns: 12,
          createdAt: now,
          updatedAt: now,
        });
        idMap.set(entry.id, taskId);
        inserted.push({ taskId, dependsOn: entry.dependencies ?? [] });
      }
      for (const { taskId, dependsOn } of inserted) {
        const resolved = dependsOn
          .map((depId) => idMap.get(depId))
          .filter((id): id is Id<"codeTasks"> => id !== undefined);
        if (resolved.length > 0) await ctx.db.patch(taskId, { dependencies: resolved });
      }
      await ctx.db.insert("codeRunEvents", { runId, type: "run.created", content: `Run created with a ${args.plan.length}-task plan.`, createdAt: now });
      await ctx.scheduler.runAfter(0, dispatchReadyRef, { runId });
      return { runId };
    }

    // The normal path: no plan was handed in, so the run builds its own. That
    // is a model call, which a mutation cannot make — planRun (an action) does
    // it and writes the tasks back. Planning is the ONLY sequential step in a
    // run; everything after it is decided by the dependency graph.
    await ctx.db.insert("codeRunEvents", { runId, type: "run.created", content: "Run created — planning.", createdAt: now });
    await ctx.scheduler.runAfter(0, planRunRef, { runId });
    return { runId };
  },
});

