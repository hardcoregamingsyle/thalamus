// Turns the Planner's JSON into task rows. Ids in the plan are the Planner's
// own strings; they become real Convex ids here, in the same two passes
// startRun uses and for the same reason — dependencies are typed
// v.id("codeTasks") and no id exists until its row is inserted.
export const savePlan = internalMutation({
  args: {
    runId: v.id("codeRuns"),
    tasks: v.array(
      v.object({
        id: v.string(),
        title: v.string(),
        description: v.optional(v.string()),
        agent: v.string(),
        dependencies: v.array(v.string()),
      }),
    ),
    summary: v.string(),
  },
  handler: async (ctx, args) => {
    const run = await ctx.db.get(args.runId);
    if (!run) return;
    if (TERMINAL_RUN_STATUSES.has(run.status) || run.cancellationRequested) return;
    const now = Date.now();

    const idMap = new Map<string, Id<"codeTasks">>();
    const inserted: { taskId: Id<"codeTasks">; dependsOn: string[] }[] = [];
    for (const t of args.tasks) {
      const taskId = await ctx.db.insert("codeTasks", {
        runId: args.runId,
        title: t.title,
        description: t.description,
        agent: t.agent,
        status: "queued",
        dependencies: [],
        allowedTools: ["filesystem"],
        maxTurns: 1,
        createdAt: now,
        updatedAt: now,
      });
      idMap.set(t.id, taskId);
      inserted.push({ taskId, dependsOn: t.dependencies });
    }
    for (const { taskId, dependsOn } of inserted) {
      const resolved = dependsOn
        .map((d) => idMap.get(d))
        .filter((id): id is Id<"codeTasks"> => id !== undefined && id !== taskId);
      if (resolved.length > 0) await ctx.db.patch(taskId, { dependencies: resolved });
    }

    await ctx.db.patch(args.runId, { summary: args.summary, updatedAt: now });
    await ctx.db.insert("codeRunEvents", {
      runId: args.runId,
      type: "run.planned",
      content: `Plan ready — ${args.tasks.length} task(s). ${args.summary}`,
      createdAt: now,
    });
    await ctx.scheduler.runAfter(0, dispatchReadyRef, { runId: args.runId });
  },
});

// The answer exit: the request was a question, so the run completes with no
// tasks at all. It is still a run row with an event, because someone who asked
// a question should find the answer in the same place as every other result
// rather than have it vanish.
export const answerRun = internalMutation({
  args: { runId: v.id("codeRuns"), answer: v.string() },
  handler: async (ctx, args) => {
    const run = await ctx.db.get(args.runId);
    if (!run || TERMINAL_RUN_STATUSES.has(run.status) || run.cancellationRequested) return;
    const now = Date.now();
    await ctx.db.patch(args.runId, { status: "completed", summary: args.answer, updatedAt: now });
    await ctx.db.insert("codeRunEvents", {
      runId: args.runId,
      type: "run.answered",
      content: args.answer,
      createdAt: now,
    });
  },
});

// A run that cannot be planned has to end saying so. Silence here would leave
// a run "queued" with no tasks and nothing scheduled — invisible forever.
export const failRun = internalMutation({
  args: { runId: v.id("codeRuns"), reason: v.string() },
  handler: async (ctx, args) => {
    const run = await ctx.db.get(args.runId);
    if (!run || TERMINAL_RUN_STATUSES.has(run.status)) return;
    const now = Date.now();
    await ctx.db.patch(args.runId, { status: "failed", updatedAt: now });
    await ctx.db.insert("codeRunEvents", { runId: args.runId, type: "run.failed", content: args.reason, createdAt: now });
  },
});

// Planning: the one sequential step. Everything after it is decided by the
// dependency graph, so this is where a run's parallelism is won or lost — a
// plan that chains every task is a turn-wise pipeline wearing a graph's
// clothes, which is what lib/parallelAgents.ts's planner prompt pushes against.
export const planRun = internalAction({
  args: { runId: v.id("codeRuns") },
  handler: async (ctx, args) => {
    try {
      const context = await ctx.runQuery(getRunContextRef, { runId: args.runId });
      if (!context) return;
      const { run, files } = context;
      if (TERMINAL_RUN_STATUSES.has(run.status) || run.cancellationRequested) return;

      const result = await callModel(
        buildOrchestratorPrompt(run.prompt, files),
        ORCHESTRATOR_SYSTEM_PROMPT,
        "Planner",
        ctx,
      );

      // Two exits, and which one was taken is read off the output itself. A
      // JSON plan means build it; prose means the request was a question and
      // is already answered. Not every request is a project — "why is my build
      // failing" wants an answer, not a five-task plan with a Tester on it.
      const parsed = parsePlannerOutput(result.text);
      if (!parsed || parsed.tasks.length === 0) {
        const answer = result.text.trim();
        if (!answer) {
          await ctx.runMutation(failRunRef, {
            runId: args.runId,
            reason: "The orchestrator returned nothing — no answer and no plan.",
          });
          return;
        }
        await ctx.runMutation(answerRunRef, { runId: args.runId, answer });
        return;
      }

      // Sorting into dependency order is not required for correctness — the
      // scheduler reads the graph, not the array — but it makes the board read
      // top-to-bottom, and it is where a cycle or a dangling id gets caught
      // before it becomes a stuck run.
      const ordered = orderPlannerTasks(parsed.tasks);
      await ctx.runMutation(savePlanRef, {
        runId: args.runId,
        summary: parsed.summary || "Plan ready.",
        tasks: ordered.tasks.map((t, i) => ({
          id: String(t.id ?? `t${i}`),
          title: String(t.title ?? `Task ${i + 1}`).slice(0, 300),
          description: t.description ? String(t.description) : undefined,
          agent: normalizeAgent(String((t as { agent?: string }).agent ?? "Coder")),
          dependencies: (t.dependencies ?? []).map(String),
        })),
      });
    } catch (err) {
      await ctx.runMutation(failRunRef, {
        runId: args.runId,
        reason: `Planning failed: ${err instanceof Error ? err.message : String(err)}`,
      });
    }
  },
});

// Queues a task's commands and hands back their ids. The executors are not
// touched: both the GitHub Actions worker (claimPendingCommandsForVm) and the
// desktop local executor (listPendingForBranch) claim by BRANCH, so a parallel
// run's commands are picked up with no change to either. The taskId exists for
// the other direction — several tasks can have commands in flight on one branch
// at once, and each needs to recognise its own results.
export const queueTaskCommands = internalMutation({
  args: {
    branchId: v.string(),
    taskId: v.id("codeTasks"),
    agent: v.string(),
    commands: v.array(v.string()),
  },
  handler: async (ctx, args) => {
    const now = Date.now();
    const ids: Id<"codeCommands">[] = [];
    for (const command of args.commands) {
      ids.push(
        await ctx.db.insert("codeCommands", {
          branchId: args.branchId,
          taskId: args.taskId,
          agent: args.agent,
          command,
          status: "pending",
          createdAt: now,
        }),
      );
    }
    return ids;
  },
});

export const getTaskCommandsInternal = internalQuery({
  args: { ids: v.array(v.id("codeCommands")) },
  handler: async (ctx, args) => {
    const rows = await Promise.all(args.ids.map((id) => ctx.db.get(id)));
    return rows
      .filter((r): r is Doc<"codeCommands"> => r !== null)
      .map((r) => ({
        command: r.command,
        status: r.status,
        output: r.output,
        exitCode: r.exitCode,
      }));
  },
});

// Read-only lookup an action needs to build a task's prompt: the run, the
// task itself, and the completed dependency tasks whose results feed it.
export const getTaskContextInternal = internalQuery({
  args: { runId: v.id("codeRuns"), taskId: v.id("codeTasks") },
  handler: async (ctx, args) => {
    const run = await ctx.db.get(args.runId);
    const task = await ctx.db.get(args.taskId);
    if (!run || !task || task.runId !== args.runId) return null;
    const dependencies = (await Promise.all(task.dependencies.map((id) => ctx.db.get(id)))).filter(
      (d): d is Doc<"codeTasks"> => d !== null,
    );
    return { run, task, dependencies, files: await branchFiles(ctx, run.branchId) };
  },
});

// Executes exactly one task's agent turn. This is the unit of concurrency:
// dispatchReady schedules one of these per ready task, so N scheduled actions
// is how N tasks actually run at the same time.
export const runTask = internalAction({
  args: { runId: v.id("codeRuns"), taskId: v.id("codeTasks") },
  handler: async (ctx, args) => {
    const startedAt = Date.now();
    const remainingMs = () => TASK_WALL_CLOCK_MS - (Date.now() - startedAt);
    try {
      const context = await ctx.runQuery(getTaskContextRef, args);
      if (!context) return; // run or task vanished (e.g. deleted mid-flight) — nothing to execute
      const { run, task, dependencies, files } = context;

      // Cancellation can land between dispatch and this action starting. The
      // model call is the expensive part of a run, so check before spending it
      // rather than discarding the answer afterwards.
      if (TERMINAL_RUN_STATUSES.has(run.status) || run.cancellationRequested) return;

      const agent = normalizeAgent(task.agent);
      const basePrompt = buildTaskPrompt({
        goal: run.prompt,
        title: task.title,
        description: task.description,
        // Only completed dependencies carry a usable report. A failed or
        // blocked one has nothing to hand over, and the scheduler would not
        // have started this task behind it anyway.
        upstream: dependencies
          .filter((d) => d.status === "completed")
          .map((d) => ({ title: d.title, agent: d.agent, result: d.result })),
        files,
      });

      // A task is a LOOP, not a single call: write code, run the build, read
      // the output, fix it. That loop is the whole reason commands exist here —
      // without it an agent can only claim its work is correct. maxTurns is the
      // per-task bound; the wall clock is the real one, because this action
      // dies at Convex's 10-minute ceiling regardless of turns remaining.
      const maxTurns = Math.min(Math.max(task.maxTurns || DEFAULT_TASK_TURNS, 1), MAX_TASK_TURNS);
      const wrote = new Set<string>();
      const removed = new Set<string>();
      const reports: string[] = [];
      let feedback = "";
      let executorReady: boolean | null = null;

      for (let turn = 1; turn <= maxTurns; turn++) {
        if (remainingMs() < MIN_TURN_MS) break;

        const result = await callModel(
          feedback ? `${basePrompt}\n\n${feedback}` : basePrompt,
          systemPromptFor(agent),
          agent,
          ctx,
          { deadlineMs: Math.min(TURN_MODEL_DEADLINE_MS, Math.max(remainingMs() - COMMAND_WAIT_MS, MIN_TURN_MS)) },
        );

        // This is where a task stops being prose and becomes work. Everything
        // that is not a file block or an op stays as the report dependents read.
        const parsed = parseAgentOutput(result.text, agent);
        for (const op of parsed.fileOps) {
          if (op.type === "delete") {
            await ctx.runMutation(internal.codeBranches.deleteFileByPath, {
              branchId: run.branchId,
              filepath: op.filepath,
            });
            removed.add(op.filepath);
            continue;
          }
          // A file op the parser could not give content for is a malformed op,
          // not a request for an empty file — writing "" would silently blank a
          // real file the agent meant to edit.
          if (typeof op.content !== "string") continue;
          await ctx.runMutation(internal.codeBranches.upsertFile, {
            branchId: run.branchId,
            filepath: op.filepath,
            content: op.content,
            agent,
          });
          wrote.add(op.filepath);
        }
        if (parsed.cleanContent.trim()) reports.push(parsed.cleanContent.trim());

        const commands = parsed.cmdOps.map((c) => c.command).filter((c) => c && c.trim());
        if (commands.length === 0) break; // nothing left to verify — the task is done talking
        if (turn === maxTurns || remainingMs() < COMMAND_WAIT_MS + MIN_TURN_MS) {
          reports.push(`[${commands.length} command(s) were not run — this task ran out of turns or time.]`);
          break;
        }

        // Boot the executor once per task, and only when a command is actually
        // wanted. A task that never runs anything must not pay for a VM.
        if (executorReady === null) {
          try {
            await ctx.runAction(internal.githubActionsRunner.bootVmForBranch, { branchId: run.branchId });
            executorReady = true;
          } catch {
            executorReady = false;
          }
        }
        if (executorReady === false) {
          feedback = renderCommandsUnavailable("The command executor could not be started for this branch.");
          continue;
        }

        const ids = await ctx.runMutation(queueTaskCommandsRef, {
          branchId: run.branchId,
          taskId: args.taskId,
          agent,
          commands,
        });
        const outcomes = await waitForCommands(ctx, ids, Math.min(COMMAND_WAIT_MS, Math.max(remainingMs() - MIN_TURN_MS, 0)));
        feedback = outcomes.length > 0
          ? renderCommandResults(outcomes)
          : renderCommandsUnavailable("No executor picked the commands up in time.");
      }

      const report = [
        reports.join("\n\n"),
        wrote.size > 0 ? `Files written: ${[...wrote].join(", ")}` : "",
        removed.size > 0 ? `Files deleted: ${[...removed].join(", ")}` : "",
      ]
        .filter(Boolean)
        .join("\n\n");

      await ctx.runMutation(finishTaskRef, {
        runId: args.runId,
        taskId: args.taskId,
        status: "completed",
        result: report || "(the agent produced no output)",
      });
    } catch (err) {
      // A task stuck in "running" forever would stall the whole run — any
      // throw from the lookup, the model call, or a malformed response must
      // still reach finishTask so the task is marked terminal.
      const message = err instanceof Error ? err.message : String(err);
      await ctx.runMutation(finishTaskRef, {
        runId: args.runId,
        taskId: args.taskId,
        status: "failed",
        result: message,
      });
    }
  },
});

// Records a task's terminal outcome and re-enters dispatchReady so whatever
// it just unblocked starts without waiting for anything else to poll.
export const finishTask = internalMutation({
  args: {
    runId: v.id("codeRuns"),
    taskId: v.id("codeTasks"),
    status: v.union(v.literal("completed"), v.literal("failed")),
    result: v.string(),
  },
  handler: async (ctx, args) => {
    const now = Date.now();
    const task = await ctx.db.get(args.taskId);
    if (!task) return; // deleted mid-flight — nothing left to finish
    await ctx.db.patch(args.taskId, { status: args.status, result: args.result, updatedAt: now });
    await ctx.db.insert("codeRunEvents", {
      runId: args.runId,
      taskId: args.taskId,
      type: args.status === "completed" ? "task.completed" : "task.failed",
      content: args.status === "completed" ? `"${task.title}" completed.` : `"${task.title}" failed: ${args.result}`,
      createdAt: now,
    });

    const run = await ctx.db.get(args.runId);
    if (!run) return;
    // Mirrors dispatchReady's own guard: cancellation must not be undone by a
    // task that happened to be in flight when it was requested.
    if (TERMINAL_RUN_STATUSES.has(run.status) || run.cancellationRequested) return;
    await ctx.scheduler.runAfter(0, dispatchReadyRef, { runId: args.runId });
  },
});
